export function billingCopy(lang: BillingUiLang): Copy {
  return lang === 'he' ? HE : EN;
}

export function billingUiLang(raw: string | null | undefined): BillingUiLang {
  return raw === 'he' ? 'he' : 'en';
}

export const BILLING_TABS = [
  { id: 'overview', label_key: 'tab_overview' },
  { id: 'modules', label_key: 'tab_modules' },
  { id: 'staff_licenses', label_key: 'tab_staff' },
  { id: 'billing_payments', label_key: 'tab_payments' },
  { id: 'billing_details', label_key: 'tab_details' },
  { id: 'client_processing', label_key: 'tab_client_processing' },
] as const;

export type BillingTabId = (typeof BILLING_TABS)[number]['id'];

export function resolveBillingTab(raw: string | null | undefined): BillingTabId {
  const value = String(raw ?? '').trim();
  return (BILLING_TABS.find((tab) => tab.id === value)?.id ?? 'overview') as BillingTabId;
}
